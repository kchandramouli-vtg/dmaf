/* Deploys the on-chain side of DMAF and writes js/chain-config.js, which the
   browser UI loads:

     NFToken            ISO/IEC 21000-23 reference token (deontic expressions + objects)
     Mpeg21ScmFactory   one-transaction deployer of reference `Contract`s
     DmafMediaRegistry  assets + pay-per-play, settled through Contract.payTo of the
                        asset's Smart Contract for Media or by its direct split

   Works on the local Hardhat node (npm run deploy) and on Sepolia
   (SEPOLIA_RPC_URL=… DEPLOYER_PRIVATE_KEY=… npx hardhat run chain/scripts/deploy.js --network sepolia). */
const fs = require("fs");
const path = require("path");
const hre = require("hardhat");

async function main() {
  const [deployer] = await hre.ethers.getSigners();
  const net = await hre.ethers.provider.getNetwork();

  const nft = await hre.ethers.deployContract("NFToken", ["NFToken", "NFT"]); // reference migrations/2_deploy_token.js
  await nft.waitForDeployment();
  const factory = await hre.ethers.deployContract("Mpeg21ScmFactory");
  await factory.waitForDeployment();
  const scmCodehash = hre.ethers.keccak256((await hre.artifacts.readArtifact("Contract")).deployedBytecode);
  const reg = await hre.ethers.deployContract("DmafMediaRegistry", [scmCodehash]);
  await reg.waitForDeployment();
  const receipt = await reg.deploymentTransaction().wait();

  const art = n => hre.artifacts.readArtifact(n);
  const [regA, nftA, facA, conA] = await Promise.all([art("DmafMediaRegistry"), art("NFToken"), art("Mpeg21ScmFactory"), art("Contract")]);
  const config = {
    chainId: Number(net.chainId),
    chainName: net.chainId === 31337n ? "Hardhat local" : net.name,
    rpcUrl: hre.network.config.url || "http://127.0.0.1:8545",
    address: await reg.getAddress(),
    deployBlock: receipt.blockNumber,
    deployedAt: new Date().toISOString(),
    abi: regA.abi,
    scm: {
      standard: "ISO/IEC 21000-23:2022 Smart Contracts for Media",
      nfToken: { address: await nft.getAddress(), abi: nftA.abi },
      factory: { address: await factory.getAddress(), abi: facA.abi },
      contract: { abi: conA.abi, bytecode: conA.bytecode, codehash: scmCodehash }, // reference Contract.sol (one-tx-per-token path)
    },
  };
  // MetaMask keeps its transaction history across Hardhat restarts. A new transaction whose nonce it has
  // already seen confirmed (same account, same chain id 31337) is marked Failed/Dropped in MetaMask, even
  // though the chain mines it. So on the local node every test account except the deployer starts at a
  // nonce no earlier chain has used: the current time in seconds. (The deployer stays at its own nonces,
  // so the contract addresses above don't change.)
  if (config.chainId === 31337) {
    const base = BigInt(Math.floor(Date.now() / 1000));
    let moved = 0;
    try {
      for (const s of (await hre.ethers.getSigners()).slice(1)) {
        const n = BigInt(await hre.ethers.provider.getTransactionCount(s.address));
        if (n < base) { await hre.network.provider.send("hardhat_setNonce", [s.address, "0x" + base.toString(16)]); moved++; }
      }
    } catch (e) {
      console.warn(`Couldn't move the test accounts' nonces (${e.message}) — after a restart, clear MetaMask's activity for each account`);
    }
    if (moved) console.log(`${moved} test accounts (#1 onwards) start at nonce ${base}, so MetaMask's history from earlier chains can't clash`);
  }

  const out = path.join(__dirname, "..", "..", "js", "chain-config.js");
  fs.writeFileSync(out,
    "/* Generated by chain/scripts/deploy.js — do not edit by hand. */\n" +
    "window.DMAF_CHAIN = " + JSON.stringify(config, null, 2) + ";\n");

  console.log(`NFToken (ISO/IEC 21000-23)  ${config.scm.nfToken.address}`);
  console.log(`Mpeg21ScmFactory            ${config.scm.factory.address}`);
  console.log(`DmafMediaRegistry           ${config.address}  (chain ${config.chainId}, block ${receipt.blockNumber})`);
  console.log(`Deployer: ${deployer.address}`);
  console.log(`Wrote ${path.relative(process.cwd(), out)}`);
}

main().catch(e => { console.error(e); process.exitCode = 1; });
