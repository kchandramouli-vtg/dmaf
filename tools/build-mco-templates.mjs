#!/usr/bin/env node
/* Regenerates js/mco-templates.js — the six Studio use cases — from the
   ISO/IEC 21000-23 template contracts, through the conformant parser:

     mpeg21/test/fixtures/standard/rdf/*.ttl     → parties, permissions, obligations, payments
     mpeg21/test/fixtures/standard/jsonld/*.json → Provide recipients (the Turtle
                                                   variants don't state them)

   So every template the Studio offers is exactly what the standard's
   parser reads from the standard's own files.   Run: npm run templates */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { getContractFromMCO } from "../mpeg21/lib/parser.mjs";
import { CLASS_IRI_BY_NAME, canonClass } from "../mpeg21/lib/vocab.mjs";
import { MCO_CONTEXT } from "../mpeg21/lib/jsonld-profile.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const STD = path.join(ROOT, "mpeg21", "test", "fixtures", "standard");
const META = {
  "stream-big-label": ["stream", "big", "On-demand stream", "Big label", "Record label with a direct deal with streaming services."],
  "stream-small-label": ["stream", "indie", "On-demand stream", "Indie label", "Indie label represented by a digital aggregator/distributor."],
  "stream-no-label": ["stream", "self", "On-demand stream", "Self-released", "Artist owns the sound-recording copyright and releases through a digital distributor."],
  "download-big-label": ["download", "big", "Digital sale", "Big label", "Record label with a direct deal with download stores."],
  "download-small-label": ["download", "indie", "Digital sale", "Indie label", "Indie label represented by a digital aggregator/distributor."],
  "download-no-label": ["download", "self", "Digital sale", "Self-released", "Artist owns the sound-recording copyright and releases through a digital distributor."],
};
const local = iri => String(iri || "").split(/[/#]/).pop();
const label = o => o?.metadata?.["rdfs:label"];
const actionIri = a => canonClass(CLASS_IRI_BY_NAME[a.class] || "mvco:action");

const out = [];
for (const key of Object.keys(META)) {
  const file = `use-case-${key}`;
  const c = (await getContractFromMCO(fs.readFileSync(path.join(STD, "rdf", file + ".ttl"), "utf8"))).contracts[0];
  const j = (await getContractFromMCO(fs.readFileSync(path.join(STD, "jsonld", file + ".json"), "utf8"))).contracts[0];
  const recipientByLabel = Object.fromEntries(Object.values(j.deontics).map(d => [label(d), j.actions[d.act]?.recipients?.[0]]).filter(([, r]) => r));
  const [model, tier, modelLabel, tierLabel, description] = META[key];
  const t = {
    // sourceLabel: the standard's label, without the service names some of them mention
    key, sourceId: local(c.identifier), sourceLabel: String(label(c) || "").replace(/\s*(and\s+)?use services like CD Baby or TuneCore\.?/i, "").replace(/\s+$/, ""),
    model, tier, modelLabel, tierLabel, description,
    file: `mpeg21/test/fixtures/standard/rdf/${file}.ttl`,
    // the end user first (the Studio's party table), then the contract's own order
    parties: Object.values(c.parties).map(p => ({ id: local(p.identifier), label: label(p), types: p.role ? [`mvco:${p.role}`] : [] }))
      .sort((a, b) => (b.types.includes("mvco:EndUser") ? 1 : 0) - (a.types.includes("mvco:EndUser") ? 1 : 0)),
    permissions: [], obligations: [],
  };
  for (const d of Object.values(c.deontics)) {
    const a = c.actions[d.act];
    if (d.type === "MCOPermission") {
      t.permissions.push({ label: label(d), issuer: local(d.issuer), action: actionIri(a), actionLabel: label(a), actor: local(a.actedBy), object: local(a.actedOver?.[0]) });
    } else if (a.type === "Payment") {
      t.obligations.push({ kind: "payment", label: label(d), issuer: local(d.issuer), action: actionIri(a), payer: local(a.actedBy),
        beneficiary: local(a.beneficiaries?.[0]), amount: a.amount ?? null, currency: a.currency ?? null, percentage: a.incomePercentage ?? null });
    } else {
      t.obligations.push({ kind: "provide", label: label(d), issuer: local(d.issuer), action: actionIri(a), actionLabel: label(a), actor: local(a.actedBy),
        object: local(a.actedOver?.[0]), recipient: local(recipientByLabel[label(d)] || "") || undefined });
    }
  }
  out.push(t);
}

const header = `/* ============================================================
   MPEG-21 MCO contract templates (ISO/IEC 21000-21 / 21000-23)
   GENERATED by tools/build-mco-templates.mjs (npm run templates) from
   the standard's template contracts, through the conformant parser
   (mpeg21/lib/parser.mjs). Do not edit by hand.

   The Studio edits this normalised model and re-serialises it to the
   flat MCO JSON-LD profile (mpeg21/lib/jsonld-profile.mjs).
   ============================================================ */
`;
fs.writeFileSync(path.join(ROOT, "js", "mco-templates.js"),
  header + `window.MCO_CONTEXT = ${JSON.stringify(MCO_CONTEXT, null, 2)};\n\nwindow.MCO_TEMPLATES = ${JSON.stringify(out, null, 2)};\n`);
console.log(`Wrote js/mco-templates.js — ${out.length} templates`);
for (const t of out) console.log(`  ${t.key.padEnd(22)} ${t.parties.length} parties · ${t.permissions.length} permissions · ${t.obligations.length} obligations`);
